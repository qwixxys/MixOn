import assert from 'node:assert/strict';
import { after, describe, it } from 'node:test';
import { ProviderError } from '../src/lib/http.js';
import { parseArtTrack, parseDuration, videoToTrack, YouTubeProvider, type YtVideo } from '../src/providers/youtube.js';
import { createTestApp, FakeProvider, fakeFetch, register, track } from './helpers.js';

const video = (id: string, overrides: Partial<YtVideo['snippet']> = {}, duration = 'PT3M30S', extra: Partial<YtVideo> = {}): YtVideo => ({
  id,
  snippet: {
    title: `Song ${id}`,
    channelTitle: 'Band - Topic',
    publishedAt: '2026-10-01T10:00:00Z',
    categoryId: '10',
    liveBroadcastContent: 'none',
    thumbnails: { high: { url: `https://i.ytimg.com/vi/${id}/hqdefault.jpg` } },
    ...overrides,
  },
  contentDetails: { duration },
  status: { embeddable: true },
  ...extra,
});

describe('YouTube Music', () => {
  it('reads durations and release metadata', () => {
    assert.equal(parseDuration('PT3M21S'), 201);
    assert.equal(parseDuration('PT1H2M'), 3720);
    assert.equal(parseDuration('P0D'), 0);
    assert.deepEqual(
      parseArtTrack('Provided to YouTube by Label\n\nSong · Band · Guest\n\nAlbum Name\n\n℗ 2026 Label\n\nReleased on: 2026-09-30\n\nAuto-generated by YouTube.'),
      { title: 'Song', artist: 'Band, Guest', album: 'Album Name', releasedAt: '2026-09-30T00:00:00.000Z' },
    );
    assert.equal(parseArtTrack('Just a video'), null);
  });

  it('turns videos into tracks', () => {
    const art = videoToTrack(
      video('a1', { description: 'Provided to YouTube by Label\n\nSong · Band\n\nAlbum\n\nReleased on: 2026-09-30' }),
    );
    assert.deepEqual([art.title, art.artist, art.album, art.releasedAt], ['Song', 'Band', 'Album', '2026-09-30T00:00:00.000Z']);
    assert.equal(art.externalUrl, 'https://music.youtube.com/watch?v=a1');
    assert.equal(art.isPreview, false);

    const clip = videoToTrack(video('c1', { title: 'Band - Hit (Official Music Video)', channelTitle: 'BandVEVO' }));
    assert.deepEqual([clip.title, clip.artist], ['Hit', 'Band']);
    const plain = videoToTrack(video('p1', { title: 'Hit [4K]', channelTitle: 'Band' }));
    assert.deepEqual([plain.title, plain.artist], ['Hit', 'Band']);
  });

  describe('without a key, through the web player API', () => {
    const flex = (...runs: string[]) => ({ musicResponsiveListItemFlexColumnRenderer: { text: { runs: runs.map((text) => ({ text })) } } });
    const thumb = { musicThumbnailRenderer: { thumbnail: { thumbnails: [{ url: 'https://lh3.googleusercontent.com/c=w60-h60-l90-rj' }, { url: 'https://lh3.googleusercontent.com/c=w120-h120-l90-rj' }] } } };
    /** A song row as search results have it: "Artist • Album • 3:34". */
    const songRow = (id: string, title: string, ...info: string[]) => ({
      musicResponsiveListItemRenderer: {
        thumbnail: thumb,
        flexColumns: [flex(title), flex(...info.flatMap((x, i) => (i ? [' • ', x] : [x])))],
        playlistItemData: { videoId: id },
      },
    });
    /** A song row as playlists have it: artists, album beside, the length on the right. */
    const listRow = (id: string, title: string, length: string, grey = false) => ({
      musicResponsiveListItemRenderer: {
        flexColumns: [flex(title), flex('Band'), flex('Album')],
        fixedColumns: [{ musicResponsiveListItemFixedColumnRenderer: { text: { runs: [{ text: length }] } } }],
        playlistItemData: { videoId: id },
        ...(grey ? { musicItemRendererDisplayPolicy: 'MUSIC_ITEM_RENDERER_DISPLAY_POLICY_GREY_OUT' } : {}),
      },
    });
    const searchReply = (rows: object[]) => ({
      contents: { tabbedSearchResultsRenderer: { tabs: [{ tabRenderer: { content: { sectionListRenderer: { contents: [{ musicShelfRenderer: { contents: rows } }] } } } }] } },
    });
    const SONGS = searchReply([
      songRow('aaaaaaaaaa1', 'Song One', 'Band - Topic', 'Album', '3:34'),
      songRow('aaaaaaaaaa2', 'Teaser', 'Band', '0:15'),
      songRow('aaaaaaaaaa3', 'Talk', 'Episode', 'Show', '45:00'),
    ]);
    const ARTISTS = searchReply([
      {
        musicResponsiveListItemRenderer: {
          thumbnail: thumb,
          flexColumns: [flex('Band'), flex('Artist', ' • ', '1.53M subscribers')],
          navigationEndpoint: { browseEndpoint: { browseId: 'UCband' } },
        },
      },
    ]);
    const PAGE_ONE = {
      header: { musicResponsiveHeaderRenderer: { title: { runs: [{ text: 'Мой плейлист' }] }, secondSubtitle: { runs: [{ text: '4 songs' }, { text: ' • ' }, { text: '15 minutes' }] } } },
      contents: {
        twoColumnBrowseResultsRenderer: {
          secondaryContents: {
            sectionListRenderer: {
              contents: [
                {
                  musicPlaylistShelfRenderer: {
                    contents: [
                      listRow('bbbbbbbbbb1', 'First', '3:00'),
                      listRow('bbbbbbbbbb2', 'Gone', '2:00', true),
                      { continuationItemRenderer: { continuationEndpoint: { continuationCommand: { token: 'NEXT' } } } },
                    ],
                  },
                },
                // Suggestions under the playlist are not part of it.
                { musicCarouselShelfRenderer: { contents: [songRow('ssssssssss1', 'Suggested', 'Other', '3:00')] } },
              ],
            },
          },
        },
      },
    };
    const PAGE_TWO = {
      onResponseReceivedActions: [{ appendContinuationItemsAction: { continuationItems: [listRow('bbbbbbbbbb3', 'Third', '4:05'), listRow('bbbbbbbbbb4', 'Fourth', '3:30')] } }],
    };
    const ARTIST_PAGE = {
      contents: {
        singleColumnBrowseResultsRenderer: {
          tabs: [{ tabRenderer: { content: { sectionListRenderer: { contents: [{ musicShelfRenderer: { contents: [
            { musicResponsiveListItemRenderer: { flexColumns: [flex('Hit'), flex('Band'), flex('120M plays'), flex('Album')], playlistItemData: { videoId: 'cccccccccc1' } } },
          ] } }] } } } }],
        },
      },
    };
    const { impl, calls } = fakeFetch([
      [
        'music.youtube.com/youtubei/v1/search',
        (_url: string, init?: RequestInit) => (JSON.parse(String(init?.body)).params.startsWith('EgWKAQIg') ? ARTISTS : SONGS),
      ],
      [
        'music.youtube.com/youtubei/v1/browse',
        (_url: string, init?: RequestInit) => {
          const body = JSON.parse(String(init?.body));
          if (body.continuation === 'NEXT') return PAGE_TWO;
          return body.browseId === 'UCband' ? ARTIST_PAGE : PAGE_ONE;
        },
      ],
    ]);
    const provider = new YouTubeProvider(null, impl);

    it('works and says it is unofficial', () => {
      assert.equal(provider.isConfigured(), true);
      assert.equal(provider.unofficial, true);
      assert.equal(new YouTubeProvider('key', impl).unofficial, false);
    });

    it('searches songs and artists', async () => {
      const hits = await provider.search('band');
      assert.deepEqual(
        hits.tracks.map((x) => [x.externalId, x.title, x.artist, x.album, x.duration]),
        [['aaaaaaaaaa1', 'Song One', 'Band', 'Album', 214]],
        'the teaser is too short, the podcast episode is no song',
      );
      assert.equal(hits.tracks[0].coverUrl, 'https://lh3.googleusercontent.com/c=w544-h544-l90-rj');
      assert.equal(hits.tracks[0].externalUrl, 'https://music.youtube.com/watch?v=aaaaaaaaaa1');
      assert.deepEqual(hits.artists, [
        { externalId: 'UCband', name: 'Band', imageUrl: 'https://lh3.googleusercontent.com/c=w544-h544-l90-rj', url: 'https://music.youtube.com/channel/UCband', subtitle: '1.5M подписчиков' },
      ]);
      const sent = JSON.parse(String(calls.find((c) => c.url.includes('/search'))?.init?.body));
      assert.equal(sent.context.client.clientName, 'WEB_REMIX');
      assert.equal(sent.query, 'band');
    });

    it('finds songs to stand in for others, with a key too, as that costs no quota', async () => {
      const found = await new YouTubeProvider('key', impl).searchTracks('Band Song One', {});
      assert.deepEqual(found.map((x) => x.externalId), ['aaaaaaaaaa1']);
      assert.ok(!calls.some((c) => c.url.includes('googleapis.com')));
    });

    it('reads an artist page', async () => {
      const songs = await provider.getArtistTracks({ externalId: 'UCband', name: 'Band' });
      assert.deepEqual(songs.map((x) => [x.title, x.artist, x.album]), [['Hit', 'Band', 'Album']]);
    });

    it('imports a whole playlist, page by page, without its suggestions or songs gone from it', async () => {
      const list = await provider.importPlaylist(new URL('https://music.youtube.com/playlist?list=PLabcdefghij'));
      assert.equal(list.title, 'Мой плейлист');
      assert.deepEqual(list.tracks.map((x) => [x.title, x.duration]), [['First', 180], ['Third', 245], ['Fourth', 210]]);
      assert.deepEqual([list.total, list.fetched], [4, 4]);
      assert.equal(list.url, 'https://music.youtube.com/playlist?list=PLabcdefghij');
      const browse = calls.filter((c) => c.url.includes('/browse')).map((c) => JSON.parse(String(c.init?.body)));
      assert.ok(browse.some((b) => b.browseId === 'VLPLabcdefghij'));
    });
  });

  it('finds artist channels', async () => {
    const { impl, calls } = fakeFetch([
      ['/youtube/v3/search', { items: [{ id: { channelId: 'UC1' }, snippet: { title: 'Band - Topic', thumbnails: { high: { url: 'b.jpg' } } } }] }],
      ['/youtube/v3/channels', { items: [{ id: 'UC1', statistics: { subscriberCount: '1530000' } }] }],
    ]);
    const [artist] = await new YouTubeProvider('key', impl).searchArtists('band');
    assert.deepEqual(artist, {
      externalId: 'UC1',
      name: 'Band',
      imageUrl: 'b.jpg',
      url: 'https://music.youtube.com/channel/UC1',
      subtitle: 'Релизы (YouTube Music) · 1.5M подписчиков',
    });
    const search = new URL(calls[0].url);
    assert.deepEqual([search.searchParams.get('type'), search.searchParams.get('key')], ['channel', 'key']);
  });

  it('keeps an artist’s music uploads the embedded player can play', async () => {
    const { impl } = fakeFetch([
      ['/channels', { items: [{ id: 'UC1', contentDetails: { relatedPlaylists: { uploads: 'UU1' } } }] }],
      ['/playlistItems', { items: ['new', 'old', 'short', 'vlog', 'blocked', 'live', 'mix'].map((videoId) => ({ contentDetails: { videoId } })) }],
      [
        '/videos',
        {
          items: [
            video('old', { publishedAt: '2026-01-01T00:00:00Z' }),
            video('new', { publishedAt: '2026-10-01T00:00:00Z' }),
            video('short', {}, 'PT45S'),
            video('vlog', { categoryId: '22' }),
            video('blocked', {}, 'PT3M', { status: { embeddable: false } }),
            video('live', { liveBroadcastContent: 'live' }),
            video('mix', {}, 'PT1H5M'),
          ],
        },
      ],
    ]);
    const tracks = await new YouTubeProvider('key', impl).getArtistTracks({ externalId: 'UC1', name: 'Band' });
    assert.deepEqual(tracks.map((t) => t.externalId), ['new', 'old']);
  });

  it('searches channels and music videos with one quota-costly request', async () => {
    const { impl, calls } = fakeFetch([
      [
        '/youtube/v3/search',
        {
          items: [
            { id: { kind: 'youtube#channel', channelId: 'UC1' }, snippet: { title: 'Band - Topic' } },
            { id: { kind: 'youtube#video', videoId: 'm1' }, snippet: { title: 'Song' } },
            { id: { kind: 'youtube#video', videoId: 'vlog' }, snippet: { title: 'Vlog' } },
          ],
        },
      ],
      ['/youtube/v3/channels', { items: [{ id: 'UC1', statistics: { subscriberCount: '10' } }] }],
      ['/youtube/v3/videos', { items: [video('m1'), video('vlog', { categoryId: '22' })] }],
    ]);
    const hits = await new YouTubeProvider('key', impl).search('band');
    assert.deepEqual(hits.artists.map((a) => a.externalId), ['UC1']);
    assert.deepEqual(hits.tracks.map((t) => t.externalId), ['m1']);
    assert.equal(calls.filter((c) => c.url.includes('/search')).length, 1);
    assert.equal(new URL(calls[0].url).searchParams.get('type'), 'video,channel');
  });

  it('plays tracks as YouTube videos', async () => {
    const source = await new YouTubeProvider('key').resolveStream({ externalId: 'abc_123', streamUrl: null, extra: null });
    assert.deepEqual(source, { url: 'https://www.youtube.com/watch?v=abc_123', kind: 'youtube' });
  });

  it('understands playlist links', () => {
    const p = new YouTubeProvider('key');
    assert.equal(p.canImport(new URL('https://music.youtube.com/playlist?list=PLabcdefghij')), true);
    assert.equal(p.canImport(new URL('https://www.youtube.com/watch?v=x&list=PLabcdefghij')), true);
    assert.equal(p.canImport(new URL('https://m.youtube.com/playlist?list=OLAK5uy_abcdefghij')), true);
    assert.equal(p.canImport(new URL('https://www.youtube.com/watch?v=x')), false);
    assert.equal(p.canImport(new URL('https://www.youtube.com/watch?v=x&list=RDabcdefghijk')), false, 'personal mixes');
    assert.equal(p.canImport(new URL('https://evil.example/playlist?list=PLabcdefghij')), false);
  });

  it('imports playlists page by page, skipping deleted and blocked videos', async () => {
    const { impl, calls } = fakeFetch([
      ['/playlists', { items: [{ snippet: { title: 'Подборка', description: 'Описание' }, contentDetails: { itemCount: 4 } }] }],
      [
        '/playlistItems',
        (url: string) =>
          new URL(url).searchParams.get('pageToken')
            ? { items: [{ contentDetails: { videoId: 'v3' } }, { contentDetails: { videoId: 'gone' } }] }
            : { items: [{ contentDetails: { videoId: 'v1' } }, { contentDetails: { videoId: 'v2' } }], nextPageToken: 'P2' },
      ],
      ['/videos', { items: [video('v1'), video('v2', {}, 'PT3M', { status: { embeddable: false } }), video('v3')] }],
    ]);
    const playlist = await new YouTubeProvider('key', impl).importPlaylist(new URL('https://music.youtube.com/playlist?list=PLabcdefghij'));
    assert.equal(playlist.title, 'Подборка');
    assert.equal(playlist.url, 'https://music.youtube.com/playlist?list=PLabcdefghij');
    assert.deepEqual(playlist.tracks.map((t) => t.externalId), ['v1', 'v3']);
    assert.deepEqual([playlist.total, playlist.fetched], [4, 4]);
    assert.equal(calls.filter((c) => c.url.includes('/playlistItems')).length, 2);
  });

  it('explains quota and key errors', async () => {
    const quota = fakeFetch([['/search', { error: { code: 403, message: 'quota', errors: [{ reason: 'quotaExceeded' }] } }, 403]]);
    await assert.rejects(
      new YouTubeProvider('key', quota.impl).searchArtists('x'),
      (err: unknown) => err instanceof ProviderError && /квота/.test(err.message),
    );
    const bad = fakeFetch([['/search', { error: { code: 400, message: 'API key not valid. Please pass a valid API key.', errors: [{ reason: 'badRequest' }] } }, 400]]);
    await assert.rejects(new YouTubeProvider('key', bad.impl).searchArtists('x'), /ключ API недействителен/);
  });

  it('hands the player a YouTube source through the API', async () => {
    const { impl } = fakeFetch([
      ['/channels', { items: [{ id: 'UC1', contentDetails: { relatedPlaylists: { uploads: 'UU1' } } }] }],
      ['/playlistItems', { items: [{ contentDetails: { videoId: 'vid1' } }] }],
      ['/videos', { items: [video('vid1')] }],
    ]);
    const t = createTestApp([new YouTubeProvider('key', impl)], impl);
    try {
      const user = await register(t.request, 'listener');
      await t.request.post('/api/subscriptions').set(user.auth).send({ provider: 'youtube', externalId: 'UC1', name: 'Band' }).expect(201);
      const { id } = t.ctx.db.prepare(`SELECT id FROM tracks WHERE source = 'youtube'`).get() as { id: number };
      const source = await t.request.get(`/api/tracks/${id}/source`).set(user.auth).expect(200);
      assert.deepEqual(source.body, { url: 'https://www.youtube.com/watch?v=vid1', kind: 'youtube' });
    } finally {
      t.cleanup();
    }
  });
});

describe('carrying on without the YouTube player', () => {
  class AudioService extends FakeProvider {
    async searchTracks() {
      return [
        track('other', { title: 'Другая песня', artist: 'Band', duration: 200 }),
        track('preview', { title: 'Hit', artist: 'Band', duration: 201, isPreview: true }),
        track('long', { title: 'Hit (Extended Mix)', artist: 'Band', duration: 290 }),
        track('match', { title: 'Hit', artist: 'Band feat. Guest', duration: 203 }),
      ];
    }
  }
  const { impl } = fakeFetch([]);
  const t = createTestApp([new AudioService(), new YouTubeProvider('key', impl)], impl);
  after(t.cleanup);

  it('finds the same song as a full audio track', async () => {
    const user = await register(t.request, 'listener');
    t.ctx.sync.storeTracks([track('vid', { title: 'Hit', artist: 'Band', duration: 200, streamUrl: null })], 'youtube', null);
    const { id } = t.ctx.db.prepare(`SELECT id FROM tracks WHERE external_id = 'vid'`).get() as { id: number };
    await t.request.get(`/api/tracks/${id}/audio-version`).expect(401);
    const res = await t.request.get(`/api/tracks/${id}/audio-version`).set(user.auth).expect(200);
    assert.equal(res.body.source, 'deezer');
    assert.equal(res.body.title, 'Hit');
    assert.equal(res.body.artist, 'Band feat. Guest');
    assert.notEqual(res.body.id, id);

    t.ctx.sync.storeTracks([track('nope', { title: 'Нигде нет', artist: 'Никто', streamUrl: null })], 'youtube', null);
    const missing = t.ctx.db.prepare(`SELECT id FROM tracks WHERE external_id = 'nope'`).get() as { id: number };
    await t.request.get(`/api/tracks/${missing.id}/audio-version`).set(user.auth).expect(404);
  });

  it('finds the song on the service chosen for listening', async () => {
    const user = await register(t.request, 'chooser');
    t.ctx.sync.storeTracks([track('vid2', { title: 'Hit', artist: 'Band', duration: 200, streamUrl: null })], 'youtube', null);
    const { id } = t.ctx.db.prepare(`SELECT id FROM tracks WHERE external_id = 'vid2'`).get() as { id: number };
    await t.request.get(`/api/tracks/${id}/version?on=deezer`).expect(401);
    const res = await t.request.get(`/api/tracks/${id}/version?on=deezer`).set(user.auth).expect(200);
    assert.equal(res.body.source, 'deezer');
    assert.equal(res.body.artist, 'Band feat. Guest');
    // Already there: the track itself.
    const same = await t.request.get(`/api/tracks/${res.body.id}/version?on=deezer`).set(user.auth).expect(200);
    assert.equal(same.body.id, res.body.id);
    // Not on that service, or no such service.
    t.ctx.sync.storeTracks([track('nope2', { title: 'Нигде нет', artist: 'Никто', streamUrl: null })], 'youtube', null);
    const missing = t.ctx.db.prepare(`SELECT id FROM tracks WHERE external_id = 'nope2'`).get() as { id: number };
    const miss = await t.request.get(`/api/tracks/${missing.id}/version?on=deezer`).set(user.auth).expect(404);
    assert.match(miss.body.error, /этой песни нет/);
    await t.request.get(`/api/tracks/${id}/version?on=nowhere`).set(user.auth).expect(404);
  });
});
