export type IconName = keyof typeof ICONS;

/**
 * A Material Symbol. `filled` switches to the filled variant where one is bundled
 * (MD3 uses filled icons for selected states). Decorative unless `label` is given.
 */
export function Icon({
  name,
  size = 24,
  filled = false,
  className = '',
  label,
}: {
  name: IconName;
  /** Pixels; null lets CSS size the icon. */
  size?: number | null;
  filled?: boolean;
  className?: string;
  label?: string;
}) {
  const svg = (filled && FILLED[name]) || ICONS[name];
  return (
    <span
      className={`icon ${className}`}
      style={size ? { width: size, height: size } : undefined}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      // The markup comes from the bundled icon package, never from user input.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
